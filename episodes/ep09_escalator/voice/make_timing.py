# 声の長さ（lines.json）から、台本 json の start/end を作り直す（narration.py がこの時刻に置く）
# 9本目（7本目から写した）。間の決まり（SKILL §3）：短い声のあと 0.8 秒／場面が変わる文の前 0.8 秒／「……」で始まる文の前 0.7 秒／前の文が「？」「……」で終わるとき 0.6 秒／ほか 0.4 秒
# MARU_WORK=<作業フォルダ> python3 make_timing.py
import os, json, re
W = os.environ["MARU_WORK"]
P = W + "/stage/script/script_v2_timed.json"
L = json.load(open(P, encoding="utf-8"))
V = json.load(open(W + "/stage/voice/achernar/lines.json", encoding="utf-8"))
BEEP = {}  # この回は合言葉がないので「ピー」はなし
# 9本目：動きを見せる所は、言い終えてから動き、結果を少し止めて見せる（SKILL §3）。値は前の文との間（秒）
EXTRA = {"02-01": 1.2,                 # 跳び乗って、運ばれ始める
         "02-04": 1.0, "02-05": 0.9,   # 段の高さがずれていく
         "03-04": 1.1,                 # 1枚、また1枚……消える
         "04-03": 1.0, "04-04": 1.4,   # その瞬間……ころん → 転がって止まる
         "04-06": 0.6,
         "05-02": 2.8,                 # 題（2 秒）
         "06-04": 0.9,                 # 下の乗り口へカメラが移る
         "07-04": 1.0, "07-05": 1.0,   # ぺたっ → 運ばれる → 消える（切りかえ）
         "08-02": 1.4,                 # 横の階段を跳ねて下りる
         "08-03": 1.2,                 # 待って……出てくる
         "09-04": 1.0,                 # ふたを外す
         "10-01": 1.2,                 # 動き出す・穴へ跳び降りる
         "11-05": 1.2,                 # 鎖をたどって歩く
         "12-01": 1.0, "12-02": 1.2,   # くるっと、さかさまに
         "12-07": 0.9,                 # 跳び乗る
         "13-01": 1.2, "13-03": 0.9, "13-05": 1.0,
         "14-01": 0.9, "14-02": 1.2,   # 輪を早回しで追う
         "15-01": 1.0, "15-02": 1.0,   # 段を外して作業台に置く
         "17-03": 1.0, "17-05": 1.2,   # 乗せる → 傾く → つるっ
         "17-07": 1.0, "17-09": 0.9,   # 乗せかえる → 水平に
         "18-03": 0.8, "18-04": 0.8,
         "21-01": 0.9,                 # 昼の駅へ
         "22-02": 1.4, "22-03": 0.9, "22-04": 1.0,   # 頭が前へずれる
         "24-02": 1.0, "24-03": 1.0,   # 想像の場面：ころん
         "25-02": 1.4,                 # 冒頭の場面をもう一度
         "26-07": 1.0, "26-08": 1.0, "26-09": 0.9,
         "26-12": 0.9,
         "28-01": 0.9,
         "29-03": 1.4, "29-04": 0.9,   # ボールが入りこむ → 止まる
         "30-02": 0.9, "30-03": 1.2,
         "31-02": 0.8, "31-03": 1.2,
         "32-03": 1.4,
         "34-03": 0.9, "34-04": 0.9,   # ボタン → すうっと止まる
         "35-03": 1.2,                 # ガクン → つんのめる
         "36-05": 1.0, "36-06": 1.4,   # 転がって測る
         "38-01": 0.9,
         "39-06": 0.9,
         "40-02": 1.0, "40-03": 0.9, "40-04": 0.9, "40-05": 1.2}
t, prev = 0.5, None
for e in L:
    d = V[str(e["no"])]["dur"]
    if prev is None:
        g = 0.0
    elif e["id"] in EXTRA:
        g = EXTRA[e["id"]]
    elif e["id"] in BEEP:
        g = BEEP[e["id"]]  # 合言葉（声に出さない）を「ピー」で鳴らす時間＋見張り番の反応
    elif V[str(prev["no"])]["dur"] < 1.0:
        g = 0.8  # 短い声（「……一瞬！」など）のあとは、字幕が 1 秒以上出るように
    elif e["scene"] != prev["scene"]:
        g = 0.8
    elif e["text"].startswith("……"):
        g = 0.7
    elif re.search(r'[？?]$|……。?$', prev["text"]):
        g = 0.6
    else:
        g = 0.4
    t += g
    e["start"], e["end"] = round(t, 3), round(t + d, 3)
    e.pop("gap_before", None)
    if g >= 0.6:
        e["gap_before"] = g
    t += d
    prev = e
json.dump(L, open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print("声の合計 %.0f 秒・間を入れて %.0f 秒（%d 分 %02d 秒）" % (sum(V[k]["dur"] for k in V), t, t // 60, t % 60))
