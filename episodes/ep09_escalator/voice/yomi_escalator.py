# 9本目（エスカレーター）：台詞 → 声に読ませる文（数字をかなに。読み違えやすい漢字をかなに。字幕は元の台詞のまま）
import re
WORD = [('2024年', 'にせんにじゅうよねん'), ('1分間', 'いっぷんかん'), ('30メートル', 'さんじゅうメートル'), ('10センチ', 'じゅっセンチ'),
        ('60センチ', 'ろくじゅっセンチ'), ('5ミリ', 'ごミリ'), ('1円玉', 'いちえんだま'), ('3枚重ね', 'さんまいがさね'),
        ('1枚ずつ', 'いちまいずつ'), ('1枚外', 'いちまいはず'), ('1枚、また1枚', 'いちまい、またいちまい'), ('段1枚', 'だんいちまい'), ('1枚', 'いちまい'),
        ('1本目', 'いっぽんめ'), ('2本目', 'にほんめ'), ('1本ずつ', 'いっぽんずつ'), ('2本', 'にほん'), ('2組', 'ふたくみ'),
        ('1つ目', 'ひとつめ'), ('2つ目', 'ふたつめ'), ('3つ目', 'みっつめ'), ('4つ', 'よっつ'), ('1つ', 'ひとつ'), ('もう1人', 'もうひとり'),
        ('表を向き', 'おもてを向き'), ('両端', 'りょうはし'), ('上の端', 'うえのはし'), ('下の端', 'したのはし'), ('上と下の端', 'うえとしたのはし'),
        ('上って', 'のぼって'), ('上ってい', 'のぼってい'), ('下って', 'くだって'), ('降り口', 'おりぐち'), ('乗り口', 'のりぐち'),
        ('入口', 'いりぐち'), ('真下', 'ました'), ('真横', 'まよこ'), ('青緑', 'あおみどり'), ('冒頭', 'ぼうとう'), ('一方', 'いっぽう'),
        ('行き先', 'いきさき'), ('目じるし', 'めじるし'), ('合図', 'あいず'), ('止まらなすぎず', 'とまらなすぎず'), ('溝', 'みぞ'),
        ('跳んで', 'とんで'), ('跳ねて', 'はねて'), ('何度', 'なんど'), ('保って', 'たもって'), ('上に着く', 'うえにつく'), ('上へ', 'うえへ')]
def yomi(t):
    s = t
    for a, b in sorted(WORD, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
