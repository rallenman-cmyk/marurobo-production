# 19本目（メッセージの旅）：台詞 → 声に読ませる文（数字・英字をかなに。読み違えやすい言葉をかなに。字幕は元の台詞のまま）
import re
WORD = [('0.000秒', 'れいてんれいれいれいびょう'), ('0.0025秒', 'れいてんれいれいにごびょう'), ('0.03秒', 'れいてんれいさんびょう'),
        ('0.045秒', 'れいてんれいよんごびょう'), ('0.185秒', 'れいてんいちはちごびょう'), ('0.200秒', 'れいてんにーれいれいびょう'),
        ('0.2秒', 'れいてんにびょう'), ('100万文字', 'ひゃくまんもじ'), ('12354', 'いちまんにせんさんびゃくごじゅうよん'),
        ('12356', 'いちまんにせんさんびゃくごじゅうろく'), ('1か所', 'いっかしょ'), ('1台1台', 'いちだいいちだい'), ('1回', 'いっかい'),
        ('1本', 'いっぽん'), ('1枚目', 'いちまいめ'), ('2枚目', 'にまいめ'), ('3枚目', 'さんまいめ'), ('1枚', 'いちまい'),
        ('1番・2番・3番', 'いちばん、にばん、さんばん'), ('1秒', 'いちびょう'), ('5周', 'ごしゅう'), ('2,000個', 'にせんこ'),
        ('20万km', 'にじゅうまんキロ'), ('3メガ', 'さんメガ'), ('480文字', 'よんひゃくはちじゅうもじ'), ('Wi-Fi', 'ワイファイ'),
        ('数百mから数km', 'すうひゃくメートルからすうキロ'), ('1つ1つ', 'ひとつひとつ'), ('1つずつ', 'ひとつずつ'), ('1つ', 'ひとつ'),
        ('札', 'ふだ'), ('包み', 'つつみ'), ('粒', 'つぶ'), ('束', 'たば'), ('根元', 'ねもと'), ('送り主', 'おくりぬし'),
        ('何番目', 'なんばんめ'), ('何を', 'なにを'), ('何が', 'なにが'), ('下りて', 'おりて'), ('開きます', 'ひらきます'),
        ('一瞬', 'いっしゅん'), ('拍子ぬけ', 'ひょうしぬけ'), ('来た道', 'きたみち'), ('出番', 'でばん'), ('印', 'しるし'),
        ('空の', 'そらの'), ('空へ', 'そらへ'), ('封筒の表', 'ふうとうのおもて'), ('中身', 'なかみ'), ('地下鉄', 'ちかてつ')]
def yomi(t):
    s = t
    for a, b in sorted(WORD, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
