# 5本目（ロボット掃除機）：台詞 → 声に読ませる文（数字をかなに・読み違えやすい漢字をかなに。字幕は元の台詞のまま）
import re
WORD = [('2002年', 'にせんにねん'), ('2021年', 'にせんにじゅういちねん'),
        ('1メートル', 'いちメートル'), ('10回', 'じゅっかい'), ('1回転', 'いっかいてん'), ('1秒', 'いちびょう'),
        ('2台', 'にだい'), ('1台', 'いちだい'), ('3つ', 'みっつ'),
        ('二重', 'にじゅう'), ('見当', 'けんとう'), ('物差し', 'ものさし'), ('真上', 'まうえ'), ('空回り', 'からまわり'),
        ('描く', 'かく'), ('描い', 'かい'), ('描か', 'かか'), ('描け', 'かけ')]
def yomi(t):
    s = t
    for a, b in WORD:
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)  # 文の頭の「……」だけ消す（間は置き方であける）
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
