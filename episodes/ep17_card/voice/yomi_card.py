# 17本目（カード）：台詞 → 声に読ませる文（数字・英字をかなに。読み違えやすい言葉をかなに。字幕は元の台詞のまま）
import re
WORD = [('2025年の1年間', 'にせんにじゅうごねんのいちねんかん'), ('510億円', 'ごひゃくじゅうおくえん'), ('9割以上', 'きゅうわりいじょう'),
        ('14けたから16けた', 'じゅうよんけたからじゅうろっけた'), ('6けた', 'ろっけた'), ('1けた', 'ひとけた'), ('7けた', 'ななけた'),
        ('何十回', 'なんじゅっかい'), ('3倍', 'さんばい'), ('1台', 'いちだい'), ('1枚', 'いちまい'), ('1通', 'いっつう'),
        ('1人1人', 'ひとりひとり'), ('1つずつ', 'ひとつずつ'), ('1つ目', 'ひとつめ'), ('2つ目', 'ふたつめ'), ('3つ目', 'みっつめ'),
        ('1つ', 'ひとつ'), ('2つ', 'ふたつ'), ('3つ', 'みっつ'), ('一度', 'いちど'), ('一見', 'いっけん'), ('数日後', 'すうじつご'),
        ('会社の印', 'かいしゃのしるし'), ('別の印', 'べつのしるし'), ('札', 'ふだ'), ('影', 'かげ'), ('門番', 'もんばん'), ('台帳', 'だいちょう'),
        ('検算', 'けんざん'), ('間の数字', 'あいだのすうじ'), ('表に書いて', 'おもてにかいて'), ('後ろへ', 'うしろへ'), ('得意顔', 'とくいがお'),
        ('何のため', 'なんのため'), ('何を', 'なにを'), ('家の', 'いえの'), ('本物', 'ほんもの'), ('帽子', 'ぼうし'), ('塔', 'とう')]
def yomi(t):
    s = t
    for a, b in sorted(WORD, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    s = re.sub(r'開([けきかいく])', lambda m: 'あ' + m.group(1), s)
    s = re.sub(r'^……', '', s)
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
