# 声の長さ（lines.json）から、台本 json の start/end を作り直す（narration.py がこの時刻に置く）
# 9本目（7本目から写した）。16本目 v2 で間の決まりを替えた：同じ場面の中 0.6 秒／場面が変わる 0.9 秒／動きを見せる所は EXTRA（長い方）
# MARU_WORK=<作業フォルダ> python3 make_timing.py
import os, json, re
W = os.environ["MARU_WORK"]
P = W + "/stage/script/script_v2_timed.json"
L = json.load(open(P, encoding="utf-8"))
V = json.load(open(W + "/stage/voice/achernar/lines.json", encoding="utf-8"))
BEEP = {}  # この回は合言葉がないので「ピー」はなし
# 動きを見せる所は、言い終えてから動き、結果を少し止めて見せる（SKILL §3）。値は前の文との間（秒）
EXTRA = {  # 17本目（カード）。間（秒）＝前の文との間。動きを見せる所・場面の変わり目で長めに
         "01-03": 1.0, "01-04": 0.9,                 # 金庫へ歩く／とびらとダイヤル
         "02-01": 1.1, "02-04": 0.8, "02-05": 0.8, "02-06": 1.0,   # 次の朝／え？／金庫へ走る／開けて中を見る
         "03-01": 0.9, "03-04": 0.9,                 # 見出し／題
         "04-01": 1.0, "04-02": 0.8, "04-04": 0.8,   # 帽子かけへ跳ぶ／帽子の寄り／3 か所が光る
         "05-02": 0.8, "05-03": 0.9, "06-02": 0.9, "06-03": 0.9, "07-02": 0.9,   # 調べる・首を振る
         "08-01": 0.9, "08-02": 0.9, "09-01": 1.0,   # 3 つの × ／ころん／起きて金庫へ
         "10-02": 1.0, "10-05": 0.8, "11-01": 0.9, "11-04": 0.9, "11-05": 0.8, "11-06": 0.9,   # タイルが浮かぶ・光る・塔
         "12-01": 0.9, "12-03": 0.9,
         "13-01": 1.2, "13-03": 0.9, "13-04": 0.8, "13-06": 0.9, "13-07": 0.8, "13-11": 0.9,   # お店へ／キーを押す／ブー／ピンポン
         "14-02": 0.9, "14-03": 1.0, "14-04": 0.9, "14-05": 0.9, "14-07": 0.8, "14-10": 0.9}
t, prev = 0.5, None
for e in L:
    d = V[str(e["no"])]["dur"]
    if prev is None:
        g = 0.0
    else:
        # 16本目 v1 のコメント「テロップとテロップの間のばらつきが大きい・たまに食い気味」：
        #   同じ場面の中 0.6 秒・場面が変わる所 0.9 秒にそろえる（前は 0.4〜1.0 秒）。
        #   動きを見せる所（EXTRA）は、これより短くしない（max をとる）
        g = 0.9 if e["scene"] != prev["scene"] else 0.6     # 場面（＝台本の段落。番号の頭 2 けた）が変わる所 0.9 秒、同じ場面の中 0.6 秒
    if e["id"] in EXTRA and prev is not None:
        g = max(g, EXTRA[e["id"]])
    t += g
    e["start"], e["end"] = round(t, 3), round(t + d, 3)
    e.pop("gap_before", None)
    if g >= 0.6:
        e["gap_before"] = g
    t += d
    prev = e
json.dump(L, open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print("声の合計 %.0f 秒・間を入れて %.0f 秒（%d 分 %02d 秒）" % (sum(V[k]["dur"] for k in V), t, t // 60, t % 60))
