# 7本目（キーボード）：台詞 → 声に読ませる文（英字・数字をかなに。読み違えやすい漢字をかなに。字幕は元の台詞のまま）
import re
LET = dict(A='エー', B='ビー', C='シー', D='ディー', E='イー', F='エフ', G='ジー', H='エイチ', I='アイ', J='ジェー', K='ケー', L='エル', M='エム',
           N='エヌ', O='オー', P='ピー', Q='キュー', R='アール', S='エス', T='ティー', U='ユー', V='ブイ', W='ダブリュー', X='エックス', Y='ワイ', Z='ゼット')
WORD = [('1868年', 'せんはっぴゃくろくじゅうはちねん'), ('1872年', 'せんはっぴゃくななじゅうにねん'), ('1873年', 'せんはっぴゃくななじゅうさんねん'),
        ('1888年', 'せんはっぴゃくはちじゅうはちねん'), ('1891年', 'せんはっぴゃくきゅうじゅういちねん'), ('1893年', 'せんはっぴゃくきゅうじゅうさんねん'),
        ('1936年', 'せんきゅうひゃくさんじゅうろくねん'), ('2011年', 'にせんじゅういちねん'),
        ('150年分', 'ひゃくごじゅうねんぶん'), ('150年', 'ひゃくごじゅうねん'), ('4年後', 'よねんご'),
        ('316個分', 'さんびゃくじゅうろっこぶん'), ('302個分', 'さんびゃくにこぶん'), ('28個分', 'にじゅうはっこぶん'), ('31個分', 'さんじゅういっこぶん'),
        ('10万台', 'じゅうまんだい'), ('10本', 'じっぽん'), ('2本', 'にほん'), ('1字', 'いちじ'), ('1回', 'いっかい'), ('2段目', 'にだんめ'),
        ('1列', 'いちれつ'), ('6文字', 'ろくもじ'), ('7分の1', 'ななぶんのいち'), ('5つ', 'いつつ'), ('3つ', 'みっつ'), ('2つ', 'ふたつ'), ('1つ', 'ひとつ'),
        ('ABC 順', 'エービーシーじゅん'), ('ABC順', 'エービーシーじゅん'), ('SE', 'エスイー'),
        ('安岡孝一', 'やすおかこういち'), ('安岡', 'やすおか'), ('橙', 'だいだい'), ('鍵盤', 'けんばん'), ('道のり', 'みちのり'),
        ('役所', 'やくしょ'), ('替える', 'かえる'), ('上の列', 'うえのれつ'), ('左上', 'ひだりうえ'), ('右上', 'みぎうえ'), ('真ん中', 'まんなか'),
        ('外され', 'はずされ'), ('出来上がり', 'できあがり'), ('何年', 'なんねん'), ('何度', 'なんど'), ('跳ね', 'はね'), ('跳ば', 'とば'),
        ('試し打ち', 'ためしうち'), ('「い ろ は」', '「い、ろ、は」'), ('打ち直', 'うちなお'), ('一列', 'いちれつ')]
def yomi(t):
    s = t
    for a, b in WORD:
        s = s.replace(a, b)
    # 英字の並び（Q W E R T Y など）は読点でつなぐ。1 文字の英字は名前で読む
    s = re.sub(r'(?<![A-Za-z])([A-Z])((?: [A-Z])+)(?![A-Za-z])', lambda m: '、'.join(LET[c] for c in m.group(0).split()), s)
    s = re.sub(r'[A-Z]', lambda m: LET[m.group(0)], s)
    s = re.sub(r'^……', '', s)
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
