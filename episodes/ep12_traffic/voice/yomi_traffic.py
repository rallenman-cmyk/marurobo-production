# 12本目（渋滞）：台詞 → 声に読ませる文（数字・英字をかなに。読み違えやすい言葉をかなに。字幕は元の台詞のまま）
import re
WORD = [('120万キロ以上', 'ひゃくにじゅうまんキロいじょう'), ('30周', 'さんじゅっしゅう'), ('30分先', 'さんじゅっぷんさき'), ('30分後', 'さんじゅっぷんご'),
        ('30分も', 'さんじゅっぷんも'), ('1台1台', 'いちだい、いちだい'), ('1台ずつ', 'いちだいずつ'), ('1台', 'いちだい'), ('1本ずつ', 'いっぽんずつ'),
        ('1本', 'いっぽん'), ('100メートル', 'ひゃくメートル'), ('10秒', 'じゅうびょう'), ('1分', 'いっぷん'), ('1つ1つ', 'ひとつひとつ'),
        ('1つ', 'ひとつ'), ('3つ', 'みっつ'), ('夕方5時', 'ゆうがたごじ'), ('2020年', 'にせんにじゅうねん'), ('97%以上', 'きゅうじゅうななパーセントいじょう'),
        ('最大50%', 'さいだいごじゅっパーセント'), ('2025年4月', 'にせんにじゅうごねんしがつ'), ('20万キロ', 'にじゅうまんキロ'), ('1人', 'ひとり'),
        ('何でも', 'なんでも'), ('何か', 'なにか'), ('何を', 'なにを'), ('何が', 'なにが'), ('持ち主の印', 'もちぬしのしるし'), ('地図に印', 'ちずにしるし'),
        ('角を', 'かどを'), ('角の', 'かどの'), ('空', 'そら'), ('前の台', 'まえのだい'), ('台に', 'だいに'), ('冒頭', 'ぼうとう'), ('一方', 'いっぽう'), ('車の数', 'くるまのかず'),
        ('測っ', 'はかっ'), ('真下', 'ました'), ('下を通る', 'したをとおる'), ('上にも', 'うえにも'), ('上を見上げる', 'うえをみあげる'), ('上に', 'うえに'),
        ('感知器', 'かんちき'), ('合わせ技', 'あわせわざ'), ('網', 'あみ'), ('表して', 'あらわして'), ('誰', 'だれ'), ('町はずれ', 'まちはずれ'),
        ('国道・県道', 'こくどう、けんどう'), ('高速道路・', 'こうそくどうろ、'), ('着く', 'つく'), ('今起きた', 'いまおきた'), ('今の', 'いまの'), ('今すいて', 'いますいて'),
        ('「今」', '「いま」'), ('先の道', 'さきのみち'), ('先のこと', 'さきのこと'), ('この先', 'このさき'), ('点', 'てん')]
def yomi(t):
    s = t
    for a, b in sorted(WORD, key=lambda x: -len(x[0])):
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)
    s = s.replace('交差てん', '交差点')
    assert not re.search(r'[0-9A-Za-z%]', s), ('数字や英字が残っている', t, s)
    return s
