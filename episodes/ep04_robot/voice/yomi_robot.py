# ロボットではありません回：台詞 → 声に読ませる文（数字・英字をかなに。字幕は元の台詞のまま）
import re
WORD = [('GPT-4', 'ジーピーティーフォー'), ('ChatGPT', 'チャットジーピーティー'), ('OpenAI', 'オープンエーアイ'), ('Google', 'グーグル'), ('AI', 'エーアイ'),
        ('1851年', 'せんはっぴゃくごじゅういちねん'), ('2014年', 'にせんじゅうよねん'), ('2023年', 'にせんにじゅうさんねん'), ('2024年', 'にせんにじゅうよねん'), ('2025年', 'にせんにじゅうごねん'),
        ('99.8%', 'きゅうじゅうきゅうてんはちパーセント'), ('5割から8割', 'ごわりからはちわり'), ('9秒から15秒', 'きゅうびょうからじゅうごびょう'),
        ('1秒', 'いちびょう'), ('1問', 'いちもん'), ('2回', 'にかい'), ('16のマス', 'じゅうろくのマス'), ('何百回', 'なんびゃっかい'),
        ('1つ', 'ひとつ'), ('2つ', 'ふたつ'), ('一つずつ', 'ひとつずつ'), ('（間）', '')]
def yomi(t):
    s = t
    for a, b in WORD:
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)  # 文の頭の「……」だけ消す（間は置き方であける）
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
