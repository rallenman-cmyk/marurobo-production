# 会話と広告の回：台詞 → 声に読ませる文（数字・英字をかなに。字幕は元の台詞のまま）
import re
WORD = [('1万7千本以上', 'いちまんななせんぼんいじょう'), ('1万7千本', 'いちまんななせんぼん'), ('2018年', 'にせんじゅうはちねん'), ('2026年', 'にせんにじゅうろくねん'),
        ('Wi-Fi', 'ワイファイ'), ('iPhone', 'アイフォーン'), ('1人目', 'ひとりめ'), ('2人目', 'ふたりめ'), ('3人目', 'さんにんめ'), ('3人', 'さんにん'),
        ('1人ずつ', 'ひとりずつ'), ('2つ', 'ふたつ'), ('1枚、2枚、3枚', 'いちまい、にまい、さんまい'), ('3枚', 'さんまい'), ('何枚', 'なんまい'),
        ('6時間前', 'ろくじかんまえ'), ('一件落着', 'いっけんらくちゃく'), ('容疑者', 'ようぎしゃ'), ('鳴いて', 'ないて'),
        ('一番', 'いちばん'), ('（間）', '')]
def yomi(t):
    s = t
    for a, b in WORD:
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)  # 文の頭の「……」だけ消す（間は置き方であける）。文の中・終わりの「……」はためとして読ませる
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
