# 6本目（配膳ロボット）：台詞 → 声に読ませる文（数字をかなに・読み違えやすい漢字をかなに。字幕は元の台詞のまま）
import re
WORD = [('2022年', 'にせんにじゅうにねん'), ('1年間', 'いちねんかん'), ('約3,000台', 'やくさんぜんだい'),
        ('12番', 'じゅうにばん'), ('3つ', 'みっつ'), ('70cm', 'ななじゅっセンチ'), ('一日', 'いちにち'),
        ('物差し', 'ものさし'), ('脚', 'あし'), ('一つ目', 'ひとつめ'), ('二つ目', 'ふたつめ'),
        ('何段', 'なんだん'), ('お店', 'おみせ'), ('先輩', 'せんぱい'), ('水平', 'すいへい'), ('配膳', 'はいぜん'),
        ('応え', 'こたえ'), ('上を向いた', 'うえをむいた'), ('下がって', 'さがって')]
def yomi(t):
    s = t
    for a, b in WORD:
        s = s.replace(a, b)
    s = re.sub(r'^……', '', s)  # 文の頭の「……」だけ消す（間は置き方であける）
    assert not re.search(r'[0-9A-Za-z]', s), ('数字や英字が残っている', t, s)
    return s
