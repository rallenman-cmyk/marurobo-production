# 声の長さ（lines.json）から、台本 json の start/end を作り直す（narration.py がこの時刻に置く）
# 6本目（5本目から写した）。間の決まり（SKILL §3）：短い声のあと 0.8 秒／場面が変わる文の前 0.8 秒／「……」で始まる文の前 0.7 秒／前の文が「？」「……」で終わるとき 0.6 秒／ほか 0.4 秒
# MARU_WORK=<作業フォルダ> python3 make_timing.py
import os, json, re
W = os.environ["MARU_WORK"]
P = W + "/stage/script/script_v2_timed.json"
L = json.load(open(P, encoding="utf-8"))
V = json.load(open(W + "/stage/voice/achernar/lines.json", encoding="utf-8"))
BEEP = {}  # この回は合言葉がないので「ピー」はなし
# 5本目：動きを見せる所は、言い終えてから動き、結果を少し止めて見せる（SKILL §3）
# 6本目：動きを見せる所は、言い終えてから動き、結果を少し止めて見せる（SKILL §3）
EXTRA = {"02-01": 1.0,                 # 奥から先輩が出てくる
         "03-01": 0.9,                 # 先輩が近づいて、ぴたっと止まる
         "03-03": 1.0,                 # にらめっこのあと、少し下がる
         "03-04": 1.6,                 # 回り道して、奥の席へ
         "03-05": 0.9,                 # ラーメンを取る
         "05-01": 2.8,                 # 前にオープニング（題名 2 秒。4本目 v5 のコメント）
         "05-03": 0.9,                 # 画面の顔がにこっ
         "07-01": 0.8,                 # 店の引きの絵
         "08-03": 0.8, "08-04": 0.8,   # 番号を押す・走り出す
         "09-01": 0.9,                 # 上から見た絵へ
         "10-03": 1.2,                 # 道が引かれる
         "11-01": 0.9, "11-05": 1.1,   # 天井を見上げる・まるロボがころん
         "12-02": 1.0,                 # まわりの形が地図に重なる
         "13-03": 0.8,
         "14-02": 1.4,                 # 暗くなって、点が浮かぶ
         "14-04": 0.9,
         "16-01": 1.0, "16-02": 0.6, "16-03": 0.6,
         "18-03": 1.6, "18-04": 1.2,   # まるロボが転がる・先輩が止まる
         "19-03": 1.2,                 # テーブルのはしをよける
         "20-01": 0.8,
         "21-01": 0.9, "21-02": 0.8, "21-03": 0.8,
         "22-01": 0.9,                 # 止まる所をゆっくりもう一度
         "23-02": 1.4,                 # いすが出て、先輩が止まる
         "25-01": 1.0, "25-02": 0.8,
         "27-01": 1.0,
         "28-02": 1.0, "28-03": 1.2,   # すりすり → 怒った顔
         "29-01": 1.0,                 # まとめの前で一息
         "30-01": 1.4, "30-02": 1.0, "30-03": 0.9, "30-04": 1.5}
t, prev = 0.5, None
for e in L:
    d = V[str(e["no"])]["dur"]
    if prev is None:
        g = 0.0
    elif e["id"] in EXTRA:
        g = EXTRA[e["id"]]
    elif e["id"] in BEEP:
        g = BEEP[e["id"]]  # 合言葉（声に出さない）を「ピー」で鳴らす時間＋見張り番の反応
    elif V[str(prev["no"])]["dur"] < 1.0:
        g = 0.8  # 短い声（「……一瞬！」など）のあとは、字幕が 1 秒以上出るように
    elif e["scene"] != prev["scene"]:
        g = 0.8
    elif e["text"].startswith("……"):
        g = 0.7
    elif re.search(r'[？?]$|……。?$', prev["text"]):
        g = 0.6
    else:
        g = 0.4
    t += g
    e["start"], e["end"] = round(t, 3), round(t + d, 3)
    e.pop("gap_before", None)
    if g >= 0.6:
        e["gap_before"] = g
    t += d
    prev = e
json.dump(L, open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print("声の合計 %.0f 秒・間を入れて %.0f 秒（%d 分 %02d 秒）" % (sum(V[k]["dur"] for k in V), t, t // 60, t % 60))
