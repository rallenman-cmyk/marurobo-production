def evening_light():
    """夕方：窓（+x のかべ）の外から、橙の低い光が部屋へ差す。部屋全体は少し暗く、暖かい色（冒頭の朝の部屋と見分けがつくように）"""
    world("#E9C7A2", 0.10)
    bpy.ops.object.light_add(type='AREA', location=(4.2, 0.1, 1.55)); a_ = bpy.context.object
    a_.data.energy = 520; a_.data.size = 1.2; a_.data.color = srgb("#FF9B57")[:3]
    d_ = mathutils.Vector((1.6, 0.5, 0.1)) - a_.location; a_.rotation_euler = d_.to_track_quat('-Z', 'Y').to_euler(); a_.visible_camera = False
    for ob in bpy.data.objects:                 # 朝の明かり（太陽）を弱く・暖かく
        if ob.type == 'LIGHT' and ob.data.type == 'SUN':
            ob.data.energy *= 0.45; ob.data.color = srgb("#FFC49A")[:3]


def b_house7(cl):
    room(window=True); town_view(); evening_light()
    t_tap = s("30-03") - 0.15                           # 頭でちょんと押して開く（30-03 の札の前）
    ph, scr = phone_seq(PH, 90.0, [(0.0, os.path.join(TEX, "ph_home.png")),
                                    (t_tap + 0.15, os.path.join(TEX, "ph_mail2.png"))], glow=1.6)
    track("phone", ph, 0.0)
    # 30-02：「メール」の時刻にスマホが光って震える
    t_n = wv("30-02", "メール") - 0.2
    ev(t_n, "chime", 0.5, "phone")
    for k in range(6):
        key(ph, "rotation_euler", t_n + k * 0.06, (0, 0, R(90 + (3 if k % 2 else -3))))
    key(ph, "rotation_euler", t_n + 0.4, (0, 0, R(90)))
    # ---- まるロボ（家の中の大きさ）。はじめからスマホの前（冒頭と同じ所）で、スマホのほうを向いて休んでいる（向き直りは 2.5 秒遅れた）
    #   （「メール」が 30-02 の終わり近くで、通知に気づいてから歩くと 4〜5 秒遅れた）
    M = MaruR((1.72, 0.62, 0.0), face=90.0, s=HOUSE_S); track("maru", M.body, 0.25); track("maru_top", M.body, 0.32); track("maru_c", M.body, 0.12)
    M.surprise(t_n + 0.35)                                                       # 通知に気づく（小さく跳ねる）
    M.at(t_n + 1.2, look=-25)                                                    # スマホをのぞく
    M.push(t_tap - 0.1, 0.12); ev(t_tap + 0.05, "tap", 0.35, "phone")            # 頭でちょんと押す
    # 30-06：うれしそうに目を細め、体を左右にゆらす
    t_h = wv("30-06", "うれしそう") - 0.2
    M.squint(t_h, -0.38, 0.4); M.glow(t_h, 1.25, 0.4)                            # 黒目を少し細め、目の光を明るく（試しの絵：-0.62 まで小さくすると驚いた顔に見えた）
    M.wobble(t_h, e("30-06") + 0.2, 9, 0.5)
    # 31-01「ちょっと待って」：目を戻して止まる
    M.squint(wv("31-01", "待って") - 0.1, 0.0, 0.3); M.glow(wv("31-01", "待って") - 0.1, 0.9, 0.3)
    # 32-01：リンク（画面の青いボタン）へ体ごと前のめり → 「ぴたっ」で止まる（そのまま 0.6 秒）→ 戻す
    t_p = wv("32-01", "ぴたっ")
    M.lean(wv("32-01", "リンク") - 0.1, t_p, 24.0, hold=0.6)
    ev(t_p, "snap", 0.5, "")                                                     # 声がまねする音（鳴らす物を付けない）
    # 32-02：首をかしげて、少し下がる
    M.confused(s("32-02") + 0.2)
    M.backstep(e("32-02") - 0.6, 0.16)
    return None, M


