def _box_world(k):
    ri, lv, x = k; ry, fc = ROWS[ri]; yb = -2.4 if ry < -1 else (2.4 if ry > 1 else 0.0)
    by = yb + fc * (0.0 if yb != 0.0 else 0.21)
    return (x, by, LEVELS[lv]), fc


def take_box(sh, k, t_in, t_take, t_out, stand, face_in, from_=(1.2, -1.4), exit_=(-1.6, 0.0)):
    """影が来て、棚に硬貨を置き、箱を胸にかかえて出ていく（21-08・21-09）。箱は棚の物を消して、手の箱を出す（場面の外で一瞬にしない：手を伸ばした所で替える）"""
    SH = SHS2
    sh_key(sh, t_in - 0.06, (40.0, 40.0), 0.0, "CONSTANT"); sh_key(sh, t_in - 0.05, from_, 90.0, "CONSTANT")
    sh_key(sh, t_take - 0.9, (stand[0] - 0.6, stand[1]), 90.0); sh_key(sh, t_take - 0.55, stand, face_in)
    key(sh.arm, "rotation_euler", t_take - 0.5, (R(-60), 0, 0)); key(sh.arm, "rotation_euler", t_take, (R(-15), 0, 0))
    key(sh.arm, "rotation_euler", t_take + 0.5, (R(-20), 0, 0))
    (bx, by, bz), fc = _box_world(k)
    shelf_box = BOXES[k]
    key(shelf_box, "scale", -100.0, (1, 1, 1), "CONSTANT"); key(shelf_box, "scale", t_take, (1, 1, 1), "CONSTANT"); key(shelf_box, "scale", t_take + 0.02, (0.001,) * 3, "CONSTANT")
    cn = coin3d((bx, by, bz + 0.002)); key(cn, "scale", -100.0, (0.001,) * 3, "CONSTANT"); key(cn, "scale", t_take - 0.05, (0.001,) * 3, "CONSTANT"); key(cn, "scale", t_take, (1.6, 1.6, 1.6), "CONSTANT")
    ev(t_take, "jingle", 0.25, "shadow%d" % id(sh))
    cb = emblem_box((0, 0, 0), "emb0", 1); cb.parent = sh.root; cb.location = (0, -0.5, 0.75); cb.scale = (0.001,) * 3
    key(cb, "scale", -100.0, (0.001,) * 3, "CONSTANT"); key(cb, "scale", t_take, (0.001,) * 3, "CONSTANT"); key(cb, "scale", t_take + 0.02, (1 / SH,) * 3, "CONSTANT")
    fo = 270.0 if face_in > 90 else -90.0      # 出口（−x）を向く。近い回り方で 90 度だけ回る
    mid = (from_[0] + 0.4, (stand[1] + from_[1]) / 2)
    sh_key(sh, t_take + 0.4, stand, face_in); sh_key(sh, t_take + 0.9, stand, fo); sh_key(sh, max((t_take + t_out) / 2, t_take + 1.4), mid, fo); sh_key(sh, t_out, exit_, fo)
    sh_key(sh, t_out + 0.05, (40.0, 40.0), fo, "CONSTANT")
    return cb


def b_e(cl):
    """3章の世界：夜の道と、つきあたりの倉庫（かくれた市場）"""
    global BOXES
    night_road(); warehouse()
    special = {MYBOX: "emb0", LEFT_BOX: "emb0", SOLD[0]: "emb0", SOLD[1]: "emb0"}
    BOXES = shelves(special)
    mb = BOXES[MYBOX]; track("mybox", mb, 0.13)
    tg = price_tag(mb, 1); track("pricetag", tg, -0.09)
    bpy.ops.object.light_add(type="POINT", location=(4.6, -1.0, 0.65)); _L = bpy.context.object      # 値札を照らす小さな明かり（v1 の点検：暗くて硬貨の絵が見えなかった）
    _L.data.energy = 10.0; _L.data.color = (1.0, 0.85, 0.65); _L.data.shadow_soft_size = 0.2
    t3 = s("20-03")
    key(tg, "rotation_euler", -100.0, (0, 0, R(180)), "CONSTANT"); key(tg, "rotation_euler", e("20-03") - 0.9, (0, 0, R(180)))       # はじめは裏（白）を向く
    key(tg, "rotation_euler", e("20-03") - 0.2, (0, 0, R(-15))); key(tg, "rotation_euler", e("20-03") + 0.2, (0, 0, R(8))); key(tg, "rotation_euler", e("20-03") + 0.6, (0, 0, 0))     # のぞきこむと、くるっと表に
    track("leftbox", BOXES[LEFT_BOX], 0.13)
    # ---- 荷車と、引く影（18-01〜18-04）。2章 16-01 で箱を積んだ荷車
    SH = SHS2
    cr, whs, BED = cart((-52.0, 0.0, 0.0), 0.0); track("cart", cr, 0.5)
    bx = tag_box((0, 0, BED)); bx.parent = cr
    nameplate((0.02, 0.02, 0.14), rot=(R(65), 0, R(8)), tex="tag_maru", w=0.24, parent=bx)
    nameplate((-0.1, -0.03, 0.12), rot=(R(70), 0, R(-6)), tex="tag_cust", w=0.24, parent=bx)
    track("cartbox", bx, 0.2)
    ck = [(749.5, (-52.0, -0.1)), (s("18-02") - 0.1, (-46.5, -0.1)), (s("18-03") - 0.1, (-40.5, -0.1)), (e("18-03"), (-30.0, -0.1)), (e("18-04") + 0.2, (-24.0, -0.1)), (e("18-07"), (-14.0, -0.1))]
    roll_cart(cr, whs, ck)
    sh = shadow((40.0, 40.0, 0.0), face=90.0, s=SH); track("shadow", sh.root, 1.5 * SH)
    for t_, (x_, y_) in ck: sh_key(sh, t_, (x_ + 1.25, y_), 90.0)
    key(sh.arm, "rotation_euler", -100.0, (R(-25), 0, 0), "CONSTANT")       # 引く棒を持つ
    # 19：倉庫の前に止めた荷車（箱はもう中へ運ばれた）。影はいない
    tq = s("19-01") - 0.08
    key(cr, "location", tq - 0.01, (-14.0, -0.1, 0.0), "CONSTANT"); key(cr, "location", tq, (-2.7, -2.3, 0.0), "CONSTANT")
    key(cr, "rotation_euler", tq - 0.01, (0, 0, 0), "CONSTANT"); key(cr, "rotation_euler", tq, (0, 0, R(20)), "CONSTANT")
    key(bx, "scale", tq - 0.01, (1, 1, 1), "CONSTANT"); key(bx, "scale", tq, (0.001,) * 3, "CONSTANT")
    sh_key(sh, tq - 0.2, (ck[-1][1][0] + 1.25, ck[-1][1][1]), 90.0, "CONSTANT")      # 止まったまま（キーがないと、(40, 40) へ斜めに滑っていた）
    sh_key(sh, tq, (40.0, 40.0), 90.0, "CONSTANT")
    # ---- まるロボ
    M = MaruR((40.0, -40.0, 0.0), face=90.0); track("maru", M.body, 0.6); track("maru_top", M.body, 0.75); track("maru_c", M.body, 0.35)
    M.at(s("18-02") - 0.2, loc=(-56.0, 0.35, 0.0), face=90.0, interp="CONSTANT")
    M.run(s("18-02") + 0.1, e("18-02") + 0.2, (-50.8, 0.35))      # 計画の点検：走っても 1 秒に約 1.3 m（8 m は間に合わない）
    M.run(s("18-03") + 0.05, e("18-03"), (-43.5, 0.35))
    ta = wv("18-03", "たったったっ")
    for k in range(3): ev(ta + 0.02 + 0.27 * k, "step", 0.4, "maru_c")      # 声の「たったったっ」（走る足音を、言葉の時刻にはっきり）
    M.confused(wv("18-04", "あれ") + 0.05)
    # 19-01：倉庫の前にたどり着く（場面の替わり目で置き直す）→ 19-02：入口のはしから、そっと中をのぞく
    M.at(s("19-01") - 0.06, loc=(-2.7, 0.45, 0.0), face=90.0, interp="CONSTANT")
    M.walk(s("19-01") + 0.2, e("19-01") + 0.3, (-0.75, 0.45))      # 計画の点検：2 回に分けると 2 秒遅れた → 1 回で、入口のはしまで
    M.peer(s("19-02") + 0.6, 1.8)      # 入口のはしに着いてから、そっとのぞく（はじめ歩く前にのぞかせ、6 秒遅れた）
    # 19-03（棚の寄りで、まるロボは映らない）の替わり目で中の通路へ置き直し、19-04〜19-06 でおそるおそる歩いて、自分のお城の箱の前へ
    #   計画の点検：まるロボは歩きで 1 秒に約 0.5 m・向きを変えるのに約 1.7 秒。入口から歩くと 6 秒遅れた
    M.at(s("19-03") + 0.1, loc=(1.2, -1.35, 0.0), face=90.0, interp="CONSTANT")
    M.walk(s("19-04") + 0.2, s("19-05") + 3.0, (4.0, -1.4))
    M.walk(s("19-06") + 0.2, s("20-01") - 0.6, (MARU_AT_BOX[0], MARU_AT_BOX[1]))
    M.at(s("20-01") - 0.3, face=180.0)
    M.surprise(wv("20-01", "見つけ") + 0.2)
    M.peer(s("20-03") + 0.3, 2.2)                     # おそるおそる、のぞきこむ
    tz = wv("20-05", "ずこっ")
    M.act(tz - 0.25, "tumble_back", lift=0.05)                  # 「ずこっ」で後ろへ転ぶ
    ev(tz + 0.05, "thud", 0.3, "maru_c")
    M.act(s("20-06") - 0.1, "get_up")
    M.at(s("20-06") + 3.2, face=60.0)                  # 起きたら、通路（カメラ）のほうへ向き直る（背中だけでは、しょんぼりが見えない）
    M.sigh(s("20-06") + 3.4, sound=False)             # しょんぼり（電子音なし。2章 v7）
    M.confused(wv("21-03", "なぜ") + 0.1)
    # 21-05 の場面の替わり目で、通路のわきへ（21-08 で影が箱の前に来る）
    M.at(s("21-05") - 0.07, loc=(MARU_ASIDE[0], MARU_ASIDE[1], 0.0), face=216.0, interp="CONSTANT")
    # ---- 21-08〜21-09：影が来て、硬貨を置いて箱を持っていく。まるロボは首で追う
    s1 = shadow((40.0, 40.0, 0.0), face=90.0, s=SH); track("shadow1", s1.root, 1.5 * SH)
    t8 = s("21-08")
    take_box(s1, MYBOX, t8 + 0.05, wv("21-08", "箱ごと") + 0.1, e("21-08") + 0.2, (MYBOX[2], -0.85), 180.0)
    M.gaze(t8 + 0.6, 25.0, 1.2); M.gaze(wv("21-08", "箱ごと") + 0.6, 60.0, 1.4)
    s2 = shadow((40.0, 40.0, 0.0), face=90.0, s=SH); track("shadow2", s2.root, 1.5 * SH)
    s3 = shadow((40.0, 40.0, 0.0), face=90.0, s=SH); track("shadow3", s3.root, 1.5 * SH)
    t9 = s("21-09")
    take_box(s2, SOLD[0], t9 + 0.05, t9 + 1.5, t9 + 3.3, (SOLD[0][2], -0.85), 180.0)
    take_box(s3, SOLD[1], wv("21-09", "その次") - 0.6, wv("21-09", "その次") + 0.9, e("21-09") + 0.1, (SOLD[1][2], -1.85), 0.0, from_=(1.2, -1.9))
    M.gaze(t9 + 2.0, 45.0, 1.2); M.gaze(wv("21-09", "その次") + 1.6, 20.0, 1.0)
    M.at(s("21-10") + 0.2, face=135.0)                # 残った箱のほうを向く
    M.sigh(s("21-10") + 2.2, sound=False)
    return sh, M


