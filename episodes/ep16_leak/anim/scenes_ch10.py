    M.glow(s("40-01") + 0.6, 0.6, 0.8)                                            # ひと休み（目の光を少し落とす。電子音なし）
    M.surprise(t_n + 0.35); M.glow(t_n + 0.35, 0.95, 0.3)                          # 通知に気づく
    M.at(t_n + 1.0, look=-28)                                                     # スマホを見下ろす
