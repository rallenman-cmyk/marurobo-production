    track("ph10", ph, 0.0)
    ev(t_n, "chime", 0.5, "ph10")
    for k in range(6):
        key(ph, "rotation_euler", t_n + k * 0.06, (0, 0, R(3 if k % 2 else -3)))
    key(ph, "rotation_euler", t_n + 0.4, (0, 0, 0))
